<?php
/**
 * Elite Auto Dealer palette build + contrast gate.
 *
 * Reads bin/palette-sources.json (name, five card swatches and the twelve base slots of every
 * palette), derives the helper slots (bin/palette-lib.php), gates the Light and Dark tones and the
 * chrome, tries the Accent tone, and writes inc/palette-registry.php (the only runtime registry; a
 * plain PHP array).
 *
 * A palette whose Light/Dark tones or chrome fail is not offered. A palette whose Accent tone fails
 * is offered without it (patterns skip Accent; .eda-tone-accent renders light).
 *
 * Usage:  php bin/palette-build.php          write the registry, list results
 *         php bin/palette-build.php --check  exit 1 if the registry is stale, a palette fails or
 *                                            the Aurelis base differs from eda_palette_aurelis()
 *
 * @package EliteAutoDealer
 */

if ( PHP_SAPI !== 'cli' ) {
	exit;
}

// phpcs:disable WordPress.WP.AlternativeFunctions -- CLI script reading and writing local theme files.
require __DIR__ . '/palette-lib.php';

$eda_sources  = json_decode( (string) file_get_contents( __DIR__ . '/palette-sources.json' ), true );
$eda_registry = array();
$eda_report   = array();
$eda_failed   = 0;

foreach ( $eda_sources['palettes'] as $eda_slug => $eda_p ) {
	$eda_base = array_map( 'strtolower', $eda_p['base'] );
	// New palettes get helper headroom (internal target); Aurelis keeps its approved, frozen helpers.
	$eda_helpers = 'aurelis' === $eda_slug ? eda_pal_helpers( $eda_base ) : eda_pal_helpers( $eda_base, EDA_TARGET_TEXT, EDA_TARGET_UI );
	$eda_slots   = $eda_base + $eda_helpers['slots'];
	$eda_notes   = $eda_helpers['notes'];
	$eda_default = 'aurelis' === $eda_slug;

	if ( $eda_default && eda_palette_aurelis() !== $eda_base ) {
		$eda_notes[] = 'Aurelis base differs from the approved values in eda_palette_aurelis()';
	}
	$eda_fail = eda_pal_failures(
		array_merge(
			eda_pal_tone_ratios( $eda_slots, eda_palette_accent_sources( true ), 'light' ),
			eda_pal_tone_ratios( $eda_slots, eda_palette_accent_sources( true ), 'dark' ),
			eda_pal_chrome_ratios( $eda_slots )
		)
	);
	if ( $eda_default && eda_palette_aurelis() !== $eda_base ) {
		$eda_fail[] = 'Aurelis base changed';
	}
	$eda_accent_fail = eda_pal_failures( eda_pal_tone_ratios( $eda_slots, eda_palette_accent_sources( true ), 'accent' ) );
	$eda_ok          = ! $eda_fail;
	$eda_failed     += $eda_ok ? 0 : 1;
	if ( $eda_accent_fail ) {
		$eda_notes[] = 'Accent tone off: ' . implode( '; ', $eda_accent_fail );
	}

	$eda_registry[ $eda_slug ] = array(
		'name'       => $eda_p['name'],
		'default'    => $eda_default,
		'selectable' => $eda_ok,
		'colors'     => array_map( 'strtolower', $eda_p['colors'] ),
		'slots'      => $eda_slots,
		'sections'   => array(
			'dark'   => $eda_ok,
			'light'  => $eda_ok,
			'accent' => $eda_ok && ! $eda_accent_fail,
		),
		'notes'      => array_merge( $eda_notes, $eda_fail ),
	);
	$eda_report[]              = sprintf( '%-4s %-24s accent:%-3s %s', $eda_ok ? 'ok' : 'FAIL', $eda_p['name'], $eda_registry[ $eda_slug ]['sections']['accent'] ? 'yes' : 'no', $eda_ok ? '' : implode( '; ', array_slice( $eda_fail, 0, 3 ) ) );
}

$eda_php = "<?php\n/**\n * GENERATED by bin/palette-build.php from bin/palette-sources.json. DO NOT EDIT BY HAND.\n *\n * @package EliteAutoDealer\n */\n\nreturn " . var_export( $eda_registry, true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- code generation.
$eda_php = str_replace( "\r\n", "\n", $eda_php );
$eda_out = __DIR__ . '/../inc/palette-registry.php';

if ( in_array( '--check', $argv, true ) ) {
	$eda_stale = ! is_file( $eda_out ) || str_replace( "\r\n", "\n", (string) file_get_contents( $eda_out ) ) !== $eda_php;
	echo implode( "\n", $eda_report ), "\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI.
	echo $eda_stale ? "\nRegistry is stale: run php bin/palette-build.php\n" : "\nRegistry up to date.\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI.
	exit( $eda_stale || $eda_failed ? 1 : 0 );
}

file_put_contents( $eda_out, $eda_php ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- CLI build.
echo implode( "\n", $eda_report ), "\n\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- CLI.
printf( "%d palette(s), %d offered, %d with Accent sections. Wrote inc/palette-registry.php\n", count( $eda_registry ), count( array_filter( $eda_registry, static fn( $r ) => $r['selectable'] ) ), count( array_filter( $eda_registry, static fn( $r ) => $r['sections']['accent'] ) ) );
exit( $eda_failed ? 1 : 0 );
